#!/usr/bin/env python3
"""
Build the markup for the scroll-driven logo animation and inject it into index.html.

    python3 tools/build_logo_scene.py

Takes the same vector shapes as the main logo (straight from the master PDF) and
splits the striped "U" into its separate pieces. Every piece becomes its own
<svg> with the SAME viewBox as the whole logo, so when each piece sits at
"no transform" they line up pixel-for-pixel into the finished logo.

The markup is written between these markers in index.html:
    <!-- LOGO-SCENE:START --> ... <!-- LOGO-SCENE:END -->
Edit the numbers below (where each piece flies in from, when, how far it
rotates) and re-run this script. Don't edit the generated block by hand.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_logos as bl  # noqa: E402  (shares the PDF extraction + bbox helpers)

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"

# ---------------------------------------------------------------------------
# Choreography. All values are fractions of the scroll "runway" (0 = start, 1 = end).
#   from  = which side the piece starts from: (-1,0) left edge, (1,0) right edge,
#           (0,-1) top, (0,1) bottom. Values between -1 and 1 slide it along that edge.
#   rot   = degrees of rotation it starts with (settles to 0)
#   start = when it starts moving, dur = how long it takes
# ---------------------------------------------------------------------------
PIECES = [
    # name,      path index, from,          rot,  start, dur
    ("slate",    17, (-1.0, -0.85), -16, 0.02, 0.52),   # blue-grey, top of left stem
    ("orange",   21, (1.0, -0.85),   14, 0.08, 0.52),   # orange right stem
    ("bowl",     16, (0.15, 1.0),     8, 0.12, 0.55),   # black bottom of the U
    ("sage",     18, (-1.0, 0.2),   -22, 0.14, 0.50),   # light green stripe
    ("teal",     19, (-0.9, 1.0),    18, 0.18, 0.50),   # grey-green stripe
    ("navy",     20, (1.0, 0.8),    -12, 0.22, 0.50),   # deep blue swoosh
]
# Text fades in last: (name, first path index, last path index (exclusive), start, dur)
TEXT = [
    ("ultimate", 0, 7, 0.74, 0.16),     # L T I M A T E
    ("solutions", 7, 16, 0.82, 0.16),   # S O L U T I O N S
]
HOUSE_INDEX = 22


def pct(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def main():
    paths = bl.extract_paths()
    if len(paths) != 23:
        sys.exit(f"Expected 23 shapes in the PDF, found {len(paths)}")

    allb = bl.union([bl.bbox(d) for _, d in paths])
    pad = 8
    vx, vy = allb[0] - pad, allb[1] - pad
    vw, vh = allb[2] - allb[0] + 2 * pad, allb[3] - allb[1] + 2 * pad
    viewbox = f"{bl.fmt(vx)} {bl.fmt(vy)} {bl.fmt(vw)} {bl.fmt(vh)}"

    def piece_svg(cls, shapes, attrs, box):
        cx = ((box[0] + box[2]) / 2 - vx) / vw * 100
        cy = ((box[1] + box[3]) / 2 - vy) / vh * 100
        hw = (box[2] - box[0]) / vw * 100
        hh = (box[3] - box[1]) / vh * 100
        body = "".join(f'<path fill="{f}" d="{d}"/>' for f, d in shapes)
        return (
            f'<svg class="piece {cls}" viewBox="{viewbox}" aria-hidden="true" focusable="false" '
            f'style="transform-origin:{pct(cx)}% {pct(cy)}%" '
            f'data-cx="{pct(cx)}" data-cy="{pct(cy)}" data-w="{pct(hw)}" data-h="{pct(hh)}"{attrs}>{body}</svg>'
        )

    out = []
    house = paths[HOUSE_INDEX]
    out.append(piece_svg("piece--house", [house], ' data-piece="house"', bl.bbox(house[1])))
    for name, idx, frm, rot, start, dur in PIECES:
        shape = paths[idx]
        attrs = (f' data-piece="u" data-name="{name}" data-from="{frm[0]},{frm[1]}" '
                 f'data-rot="{rot}" data-start="{start}" data-dur="{dur}"')
        out.append(piece_svg(f"piece--{name}", [shape], attrs, bl.bbox(shape[1])))
    for name, a, b, start, dur in TEXT:
        shapes = paths[a:b]
        box = bl.union([bl.bbox(d) for _, d in shapes])
        attrs = f' data-piece="text" data-name="{name}" data-start="{start}" data-dur="{dur}"'
        out.append(piece_svg(f"piece--{name}", shapes, attrs, box))

    block = (
        "<!-- LOGO-SCENE:START (generated by tools/build_logo_scene.py - edit that script, not this block) -->\n"
        + "\n".join(out)
        + "\n<!-- LOGO-SCENE:END -->"
    )
    html = INDEX.read_text()
    new, n = re.subn(r"<!-- LOGO-SCENE:START.*?<!-- LOGO-SCENE:END -->", lambda m: block, html, flags=re.S)
    if n != 1:
        sys.exit("Could not find the LOGO-SCENE markers in index.html")
    INDEX.write_text(new)
    # Aspect ratio the CSS needs (kept in one place)
    print(f"Injected {len(out)} pieces. Logo aspect ratio: {bl.fmt(vw)} / {bl.fmt(vh)} = {vw / vh:.4f}")


if __name__ == "__main__":
    main()
